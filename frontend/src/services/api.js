import axios from 'axios';

const API_BASE_URL = import.meta.env.VITE_API_URL || (typeof window !== 'undefined' && window.location.port !== '5173' ? '' : 'http://localhost:8000');

const apiClient = axios.create({
  baseURL: API_BASE_URL,
  timeout: 60000,
  headers: {
    'Content-Type': 'application/json',
  },
});

export const apiService = {
  // Check root status and project version
  getRoot: async () => {
    const response = await apiClient.get('/');
    return response.data;
  },

  // Check health status
  getHealth: async () => {
    const response = await apiClient.get('/api/health');
    return response.data;
  },

  // Fetch connected banks info
  getBanks: async () => {
    const response = await apiClient.get('/api/banks');
    return response.data;
  },

  // Fetch synthetic transactions
  getTransactions: async () => {
    const response = await apiClient.get('/api/transactions');
    return response.data;
  },

  // Fetch real-time live transactions feed
  getLiveTransactions: async (count = 1, history = false) => {
    const response = await apiClient.get('/api/v2/transactions/live', {
      params: { count, history }
    });
    return response.data;
  },

  // Fetch mock alerts
  getAlerts: async () => {
    const response = await apiClient.get('/api/alerts');
    return response.data;
  },

  // Fetch real-time live alerts feed generated by the fraud detection engine
  getLiveAlerts: async (history = true) => {
    const response = await apiClient.get('/api/v2/alerts/live', {
      params: { history }
    });
    return response.data;
  },

  // --- Stage 2A: Simulation, Graph & Detection Engine Endpoints ---

  // Fetch simulated transactions with detection scores
  getSimulation: async (params = {}) => {
    const response = await apiClient.get('/api/v2/simulate', { params });
    return response.data;
  },

  // Fetch cross-bank NetworkX transaction graph
  getGraph: async (params = {}) => {
    const response = await apiClient.get('/api/v2/graph', { params });
    return response.data;
  },

  // Fetch real-time live network graph incorporating streaming transactions
  getLiveGraph: async (params = {}) => {
    const response = await apiClient.get('/api/v2/graph/live', { params });
    return response.data;
  },

  // Fetch rule definitions and detection summary
  getDetection: async () => {
    const response = await apiClient.get('/api/v2/detect');
    return response.data;
  },

  // Fetch genuine precision, recall, F1 metrics from ground truth
  getMetrics: async (threshold = 65) => {
    const response = await apiClient.get('/api/v2/metrics', { params: { threshold } });
    return response.data;
  },

  // --- Stage 2B: GraphSAGE GNN Inference, Metrics & Baseline Comparison ---

  // Fetch node-level GNN predictions for all 150 accounts (blind inference)
  getGnnPredict: async () => {
    const response = await apiClient.get('/api/v2/gnn/predict');
    return response.data;
  },

  // Fetch GNN test-set evaluation metrics & confusion matrix
  getGnnMetrics: async () => {
    const response = await apiClient.get('/api/v2/gnn/metrics');
    return response.data;
  },

  // Fetch fair apples-to-apples comparison on identical test nodes (Rule vs GNN)
  getGnnCompare: async () => {
    const response = await apiClient.get('/api/v2/gnn/compare');
    return response.data;
  },

  // --- Stage 2C-1: Private Set Intersection (PSI) Cryptographic Layer ---

  // Fetch bank vaults summary and non-confidential crypto parameters
  getPsiVaults: async () => {
    const response = await apiClient.get('/api/v2/privacy/psi/vaults');
    return response.data;
  },

  // Execute multi-bank commutative Diffie-Hellman PSI protocol
  runPsiProtocol: async () => {
    const response = await apiClient.post('/api/v2/privacy/psi/run');
    return response.data;
  },

  // Fetch latest PSI results
  getPsiResults: async () => {
    const response = await apiClient.get('/api/v2/privacy/psi/results');
    return response.data;
  },

  // Rotate bank keys and reset session
  resetPsiSession: async () => {
    const response = await apiClient.post('/api/v2/privacy/psi/reset');
    return response.data;
  },

  // --- Stage 2C-2: Federated Learning with Paillier Homomorphic Encryption ---

  // Fetch FL system status, round number, and public key parameters
  getFederatedStatus: async () => {
    const response = await apiClient.get('/api/v2/federated/status');
    return response.data;
  },

  // Initialize or re-initialize FL session
  startFederatedSession: async () => {
    const response = await apiClient.post('/api/v2/federated/start');
    return response.data;
  },

  // Execute one complete encrypted FL round
  runFederatedRound: async (localEpochs = 5, lr = 0.02) => {
    const response = await apiClient.post('/api/v2/federated/round', null, {
      params: { local_epochs: localEpochs, lr: lr },
    });
    return response.data;
  },

  // Fetch round-by-round evaluation metrics
  getFederatedMetrics: async () => {
    const response = await apiClient.get('/api/v2/federated/metrics');
    return response.data;
  },

  // Fetch safe non-confidential ciphertext telemetry
  getFederatedUpdates: async () => {
    const response = await apiClient.get('/api/v2/federated/updates');
    return response.data;
  },

  // Fetch cryptographic audit metadata & threat model disclosures
  getFederatedSecurity: async () => {
    const response = await apiClient.get('/api/v2/federated/security');
    return response.data;
  },

  // Fetch measured optimization experiment benchmark results
  getFederatedBenchmark: async () => {
    const response = await apiClient.get('/api/v2/federated/benchmark');
    return response.data;
  },

  // Reset FL session state and rotate Paillier keypair
  resetFederatedSession: async () => {
    const response = await apiClient.post('/api/v2/federated/reset');
    return response.data;
  },

  // Fetch comprehensive empirical performance & ablation metrics
  getPerformanceMetrics: async () => {
    const response = await apiClient.get('/api/v2/metrics/performance');
    return response.data;
  },
};

export default apiClient;


